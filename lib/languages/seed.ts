/**
 * Seed teaching content — A1 starter modules, original work, kept
 * intentionally small. Each language ships with the absolute basics
 * (greetings + numbers 1-5) so the drill UI has something to render
 * out of the box. Contributors can grow per-language curricula via PR.
 */

import type {
  CefrLevel,
  LanguageCode,
  LanguageLevelCurriculum,
  LevelModule,
} from "./types";

/** Empty placeholder so higher levels render a "Coming soon" state. */
const emptyLevel = (level: CefrLevel): LanguageLevelCurriculum => ({
  level,
  modules: [],
  mockCount: 0,
});

/** Build the four-level curriculum where only A1 has seed modules. */
function withA1Only(a1Modules: LevelModule[]): LanguageLevelCurriculum[] {
  return [
    { level: "A1", modules: a1Modules, mockCount: 8 },
    emptyLevel("A2"),
    emptyLevel("B1"),
    emptyLevel("B2"),
  ];
}

