/** Day-stable PRNG so the picker can shuffle distractors with the
 *  same seed semantics as the rest of the catalog. */
function mulberry32(seed: number) {
  let s = seed >>> 0;
  return () => {
    s = (s + 0x6d2b79f5) >>> 0;
    let r = s;
    r = Math.imul(r ^ (r >>> 15), r | 1);
    r ^= r + Math.imul(r ^ (r >>> 7), r | 61);
    return ((r ^ (r >>> 14)) >>> 0) / 4294967296;
  };
}

/**
 * Build a complete set of match-pair Letter exercises for a language.
 * One exercise per word in the table: the word's letter is the
 * target, and two distractors are pulled from a different starting
 * letter — so exactly one option ever matches the target.
 */
function buildLettersPool(langCode: string): Exercise[] {
  const words = LETTER_WORDS_BY_LANG[langCode];
  const tpl = LETTER_TEMPLATES[langCode];
  if (!words || !tpl) return [];
  let h = 5381;
  for (let i = 0; i < langCode.length; i++) h = (h * 33) ^ langCode.charCodeAt(i);
  const rand = mulberry32(h);
  return words.map((w, i) => {
    // Distractors: pick 2 words whose letter !== w.letter.
    const others = words.filter((o) => o.letter !== w.letter);
    // Shuffle deterministically per word index so the layout is stable.
    const seedRand = mulberry32(h ^ (i * 2654435761));
    const shuffled = others.slice();
    for (let j = shuffled.length - 1; j > 0; j--) {
      const k = Math.floor(seedRand() * (j + 1));
      [shuffled[j], shuffled[k]] = [shuffled[k]!, shuffled[j]!];
    }
    const distractors = shuffled.slice(0, 2);
    // Randomize which slot the correct answer occupies.
    const slotR = Math.floor(rand() * 3);
    const slots = [distractors[0]!, distractors[1]!, w];
    [slots[2], slots[slotR]] = [slots[slotR]!, slots[2]!];
    const correctId = ["a", "b", "c"][slotR]!;
    return {
      id: `l-${langCode}-${i}`,
      theme: "letters",
      kind: "match-pair",
      prompt: tpl.prompt(w.letter),
      reference: w.letter,
      choices: slots.map((s, ix) => ({
        id: ["a", "b", "c"][ix]!,
        emoji: s.emoji,
        label: s.word,
      })),
      correctId,
      praise: tpl.praise(w.word, w.letter),
    } satisfies Exercise;
  });
}

const LETTERS_POOL_CACHE = new Map<string, Exercise[]>();

/** Public accessor: the language-specific letter exercise pool, or []
 *  if no native pool exists for `langCode`. PlaySequence calls this
 *  to swap in the right vocab BEFORE picking; only when this returns
 *  an empty array does it fall back to the English catalog + the
 *  word-by-word translator. */
export function localizedLettersPool(langCode: string | null | undefined): Exercise[] {
  if (!langCode) return [];
  const key = langCode.toLowerCase();
  if (LETTERS_POOL_CACHE.has(key)) return LETTERS_POOL_CACHE.get(key)!;
  const pool = buildLettersPool(key);
  LETTERS_POOL_CACHE.set(key, pool);
  return pool;
}
