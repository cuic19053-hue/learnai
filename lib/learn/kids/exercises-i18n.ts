/**
 * Per-language overrides for the exercise catalog.
 *
 * Translation strategy:
 *   - Phrase table covers the common prompt templates ("How many X?",
 *     "Find the X", "Which is X?", etc.). The English original is the
 *     key; we substitute variables back in.
 *   - Word table translates choice labels (Apple, Dog, Circle, …).
 *     Same key-by-English approach.
 *   - When a phrase or word isn't in the table for the picked
 *     language, we fall back to the English original so the screen
 *     stays usable while translations land.
 *
 * `localizeExercise(exercise, lang)` returns a clone of the exercise
 * with `prompt`, `praise`, `hint`, and each `choices[].label`
 * replaced where a translation exists.
 *
 * Goal: zero mixed-language screens for Italian / Spanish / French /
 * Portuguese / German once these tables are complete. Other languages
 * fall back to English text but still get the audio in the right
 * language via SpeechSynthesisUtterance.lang.
 */

