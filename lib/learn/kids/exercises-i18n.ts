/**
 * Return a localized clone of an exercise. Falls back to the English
 * original for any field that isn't translated, so the page never
 * shows undefined text.
 */
export function localizeExercise(ex: Exercise, langCode: string | null | undefined): Exercise {
  if (!langCode) return ex;
  const pack = PACKS[langCode.toLowerCase()];
  if (!pack) return ex;
  const tr = (s: string | undefined, dict: Dict) => (s && dict[s]) || s;
  return {
    ...ex,
    prompt: tr(ex.prompt, pack.prompts) ?? ex.prompt,
    praise: tr(ex.praise, pack.prompts) ?? ex.praise,
    hint: tr(ex.hint, pack.prompts),
    choices: ex.choices.map((c) => ({
      ...c,
      label: c.label ? (tr(c.label, pack.words) ?? c.label) : c.label,
    })),
  };
}

